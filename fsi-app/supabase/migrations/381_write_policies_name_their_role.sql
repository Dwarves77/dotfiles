-- ---- Self-check: attack every touched table as anon, prove the real principals unchanged, rolled back ---------------
-- sec7_try runs one statement as anon, authenticated (with a fixture JWT subject) or service_role and returns
-- 'ok:<rows>' or 'err:<sqlstate>:<first line of the message>'; sec7_expect raises ABORT when the result does not match.
CREATE FUNCTION pg_temp.sec7_try(p_role text, p_uid uuid, p_sql text)
RETURNS text
LANGUAGE plpgsql
AS $f$
DECLARE
  v_rows integer;
BEGIN
  IF p_role = 'service_role' THEN
    SET LOCAL ROLE service_role;
  ELSIF p_role = 'anon' THEN
    SET LOCAL ROLE anon;
  ELSE
    SET LOCAL ROLE authenticated;
  END IF;
  PERFORM set_config('request.jwt.claims',
    json_build_object('sub', p_uid::text, 'role', p_role)::text, true);
  PERFORM set_config('request.jwt.claim.sub', coalesce(p_uid::text, ''), true);
  PERFORM set_config('request.jwt.claim.role', p_role, true);
  BEGIN
    EXECUTE p_sql;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    RESET ROLE;
    RETURN 'ok:' || v_rows::text;
  EXCEPTION WHEN OTHERS THEN
    RESET ROLE;
    RETURN 'err:' || SQLSTATE || ':' || split_part(SQLERRM, E'\n', 1);
  END;
END;
$f$;

CREATE FUNCTION pg_temp.sec7_expect(p_label text, p_got text, p_want_like text, p_reject_like text DEFAULT NULL)
RETURNS void
LANGUAGE plpgsql
AS $f$
BEGIN
  IF p_got NOT LIKE p_want_like OR (p_reject_like IS NOT NULL AND p_got LIKE p_reject_like) THEN
    RAISE EXCEPTION 'ABORT: % expected % but got %', p_label, p_want_like, p_got;
  END IF;
END;
$f$;

