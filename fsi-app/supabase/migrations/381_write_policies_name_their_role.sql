-- ---- Helper: does a predicate name an authenticated actor? -------------------------------------------------------
-- pg_policies prints qual and with_check in the deparsed form, so the idiom auth.role() = 'service_role' appears as
-- (( SELECT auth.role() AS role) = 'service_role'::text); the pattern allows a short gap between the call and the role
-- literal. A text match is necessary, not sufficient: the policy list was also read by eye (every predicate is an AND of
-- the actor test with the row test, or an OR of actor-keyed branches only), and the self-check attacks the result.
CREATE FUNCTION pg_temp.sec7_requires_auth(p_pred text) RETURNS boolean
LANGUAGE sql IMMUTABLE AS $f$
