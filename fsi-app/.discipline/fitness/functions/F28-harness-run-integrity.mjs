import { join } from 'node:path';
import { violation, PASS } from '../lib/result.mjs';
import { globFiles } from '../lib/glob.mjs';
import { getRepoRoot } from '../../lib/context.mjs';
import {
  validateRunArtifact, hashHarnessVersion, ALLOWED_FAMILIES, isRunArtifactFilename,
  readHarnessLedgerExport, newestLedgerRunAt, familyCurrentInLedger,
} from '../../../scripts/lib/run-artifact.mjs';
import { GOVERNING_FILES } from '../../../scripts/harness-runs/governing-files.mjs';
import { FAMILIES } from '../../../scripts/harness-runs/family-registry.mjs';
import { BUILD_MODE } from '../../governance/build-mode.mjs';

const HARNESS_RUNS_REL = 'fsi-app/scripts/harness-runs';

// Governing files per family, fsi-app-relative - see governing-files.mjs's own header for the "wrong
// copy of the truth" defect this single import closes (this array used to be either hardcoded here or
// hand-copied into each family's own runner script, and the two copies proved live to have drifted for
// mint). Every family's own canonical runner script AND this file both import the SAME array.
export { GOVERNING_FILES };

const PROPOSER_PASS_FILE = 'LAST-PROPOSER-PASS.md';

const DAY_MS = 24 * 60 * 60 * 1000;
/** Days a family may go without a current ledger row before currency fails (BUILD_MODE widens it). */
export const CURRENCY_WINDOW_DAYS = 30;
export const CURRENCY_WINDOW_DAYS_BUILD_MODE = 90;

/**
 * Parse every *.json artifact file grouped by family from a flat { path -> content } map (repo-relative
 * paths under HARNESS_RUNS_REL/<family>/<file>.json). Pure - no I/O - so the red-tests can drive it with
 * a constructed fixture tree instead of only the live repo (F23/F25/F27's negative-test discipline).
 * Returns { byFamily: Map<family, { valid: object[], invalid: {file, reason}[] }> }.
 */
export function scanArtifacts(fileContents) {
  const byFamily = new Map();
  for (const [path, content] of Object.entries(fileContents)) {
    const rel = path.startsWith(`${HARNESS_RUNS_REL}/`) ? path.slice(HARNESS_RUNS_REL.length + 1) : path;
    const parts = rel.split('/');
    // parts.length !== 2 excludes anything not a DIRECT child of a family directory - a family's own
    // family.json and its traces/ subdirectory both fail this check: <family>/traces/<file> is THREE
    // parts, never two. isRunArtifactFilename (lane N2, 2026-09-19, Amendment 2) then matches the
    // convention's <family>-run-NNN.json shape and nothing else, so a family's own family.json
    // descriptor is never scanned as a run-artifact candidate either. Both are proven directly by this
    // file's own test, not left to the reader to infer from the two predicates alone.
    if (parts.length !== 2 || !isRunArtifactFilename(parts[1])) continue; // not a family-level artifact file
    const [family, file] = parts;
    if (!byFamily.has(family)) byFamily.set(family, { valid: [], invalid: [] });
    const bucket = byFamily.get(family);
    let parsed;
    try {
      parsed = JSON.parse(content);
    } catch (err) {
      bucket.invalid.push({ file, reason: `unparseable JSON: ${err.message}` });
      continue;
    }
    const errors = validateRunArtifact(parsed);
    if (errors.length) {
      bucket.invalid.push({ file, reason: errors.join('; ') });
      continue;
    }
    bucket.valid.push(parsed);
  }
  return { byFamily };
}

/** Rule (a): every artifact file must validate. Pure comparator over scanArtifacts()'s output. */
export function auditSchema(byFamily) {
  const problems = [];
  for (const [family, { invalid }] of byFamily) {
    for (const { file, reason } of invalid) {
      problems.push(
        `INVALID ARTIFACT - ${HARNESS_RUNS_REL}/${family}/${file} does not validate against ` +
          `CONVENTION.md's schema (validateRunArtifact): ${reason}`,
      );
    }
  }
  return problems;
}

/**
 * Rule (b), CURRENCY (lane GATE-3, 2026-10-08). Pure comparator, injectable: the red-tests drive it with a
 * constructed ledger and a fixed reference date instead of the live export and the wall clock.
 * @param {object} p
 * @param {string} p.family
 * @param {string} p.liveHash hashHarnessVersion over the family's governing files, against the live tree
 * @param {object[]} p.ledgerRows the ledger export's rows (all families)
 * @param {boolean} p.ledgerPresent whether the export file exists and parses
 * @param {string|null} p.registered the family.json `registered` date (YYYY-MM-DD), or null if unknown
 * @param {Date} p.refDate the reference "now" (the export's capturedAt, else the wall clock)
 * @param {boolean} p.buildMode BUILD_MODE (governance/build-mode.mjs)
 * @returns {{status: 'current'|'owed'|'never-run', problems: string[], notices: string[]}}
 */
export function auditFamilyCurrency({ family, liveHash, ledgerRows, ledgerPresent, registered, refDate, buildMode }) {
  if (familyCurrentInLedger(ledgerRows, family, liveHash)) {
    return { status: 'current', problems: [], notices: [] };
  }
  const windowDays = buildMode ? CURRENCY_WINDOW_DAYS_BUILD_MODE : CURRENCY_WINDOW_DAYS;
  const newest = newestLedgerRunAt(ledgerRows, family);

  if (newest === null) {
    const where = ledgerPresent ? 'the harness ledger export holds no row for it' : 'the harness ledger export is absent';
    if (buildMode) {
      return {
        status: 'never-run',
        problems: [],
        notices: [`NOTICE [${family}]: ${where}, so nothing has run (build mode: not a failure).`],
      };
    }
    const registeredAt = registered ? Date.parse(registered) : NaN;
    const ageDays = Number.isNaN(registeredAt) ? null : Math.floor((refDate.getTime() - registeredAt) / DAY_MS);
    if (ageDays !== null && ageDays <= CURRENCY_WINDOW_DAYS) {
      return {
        status: 'never-run',
        problems: [],
        notices: [`NOTICE [${family}]: ${where}; registered ${ageDays} day(s) ago, inside the ${CURRENCY_WINDOW_DAYS}-day window.`],
      };
    }
    return {
      status: 'never-run',
      problems: [
        `NEVER RUN - harness family "${family}": ${where}, and the family is ${ageDays === null ? 'of unknown age' : `${ageDays} days past its registration`} ` +
          `(window ${CURRENCY_WINDOW_DAYS} days). Run it, then regenerate the export ` +
          `(node fsi-app/scripts/lib/export-harness-ledger.mjs) so a row at hash ${liveHash} lands.`,
      ],
      notices: [],
    };
  }

  const ageDays = Math.floor((refDate.getTime() - newest.getTime()) / DAY_MS);
  if (ageDays > windowDays) {
    return {
      status: 'owed',
      problems: [
        `STALE RUN - harness family "${family}": its governing files hash to ${liveHash}, no ledger row records that ` +
          `hash, and its newest row is ${ageDays} days old (window ${windowDays} days). The governing files changed ` +
          `after the last run and no run followed. Run the family, then regenerate the harness ledger export.`,
      ],
      notices: [],
    };
  }
  return {
    status: 'owed',
    problems: [],
    notices: [
      `NOTICE [${family}]: governing files hash to ${liveHash} but no ledger row records it; newest row ${ageDays} day(s) old, inside the ${windowDays}-day window, so a run is owed.`,
    ],
  };
}

/** Rule (c): a family with 2 or more valid artifacts must have a LAST-PROPOSER-PASS.md naming the latest run_id. */
export function auditProposerAttestation(family, validArtifacts, proposerPassContent) {
  if (validArtifacts.length < 2) return [];
  const latest = [...validArtifacts].sort((a, b) => Date.parse(a.started_at) - Date.parse(b.started_at)).at(-1);
  if (proposerPassContent == null) {
    return [
      `NO PROPOSER ATTESTATION - harness family "${family}" has ${validArtifacts.length} artifacts but no ` +
        `${HARNESS_RUNS_REL}/${family}/${PROPOSER_PASS_FILE}. PROPOSER-RUNBOOK.md's precondition (read the ` +
        `full prior record before the next run) is machine-checkable once a family has 2 or more runs to compare - ` +
        `write ${PROPOSER_PASS_FILE} naming ${latest.run_id} and the hypotheses/proposal(s) read from it, or ` +
        `"none warranted" with basis.`,
    ];
  }
  if (!proposerPassContent.includes(latest.run_id)) {
    return [
      `STALE PROPOSER ATTESTATION - ${HARNESS_RUNS_REL}/${family}/${PROPOSER_PASS_FILE} does not name ` +
        `${latest.run_id} (the family's latest artifact). A proposer pass that does not name the run it ` +
        `read is indistinguishable from one that read an older run, or none.`,
    ];
  }
  return [];
}

function readIfExists(path) {
  return existsSync(path) ? readFileSync(path, 'utf8') : null;
}

/**
 * Hash one family's GOVERNING_FILES, converting a missing file into a NAMED fitness failure instead of
 * letting hashHarnessVersion's raw ENOENT (it does a plain readFileSync per listed file, by design - see
 * its own doc comment in scripts/lib/run-artifact.mjs) escape check() as an unhandled throw. Before this,
 * a single missing governing file (a typo'd path in GOVERNING_FILES, a file renamed without updating this
 * table, or a family whose governing files a DIFFERENT lane is still expected to land) would abort
 * check() for EVERY family and EVERY other rule in the same pass with an opaque Node stack trace, not a
 * fitness-function violation a coordinator can act on. Only ENOENT is translated here - any other
 * hashHarnessVersion failure still propagates unchanged, since silently swallowing those would hide a
 * genuine bug in F28 itself rather than report the legitimate "this family's governing file set doesn't
 * match the tree yet" state this exists to name.
 * Returns { hash: string|null, problems: string[] } - `hash` is null exactly when `problems` is non-empty.
 * Exported so this ENOENT-to-named-failure conversion is unit-testable without a full repo-root check().
 */
export function safeHashGoverningFiles(family, governing, baseDir) {
  try {
    return { hash: hashHarnessVersion(governing, baseDir), problems: [] };
  } catch (err) {
    if (err && err.code === 'ENOENT') {
      return {
        hash: null,
        problems: [
          `MISSING GOVERNING FILE - harness family "${family}"'s entry in F28's GOVERNING_FILES names a ` +
            `file that does not exist on the current tree (${err.message}). Land the missing file, or ` +
            `if it was intentionally renamed/removed, correct that family's own family.json.`,
        ],
      };
    }
    throw err;
  }
}

export const fitnessFunction = {
  id: 'F28',
  name: 'harness-run-integrity',
  description:
    'Every scripts/harness-runs/*/*.json artifact validates against CONVENTION.md\'s schema; a harness ' +
    'family is current when the harness ledger export holds a row whose governing_hash equals the family\'s ' +
    'live governing-file hash (a family that is not current fails only when its newest ledger row is older ' +
    'than 30 days, 90 in build mode; a family with no ledger row at all is a notice in build mode and fails ' +
    'outside it once 30 days past registration); a family with 2 or more artifacts carries a ' +
    'LAST-PROPOSER-PASS.md naming the latest run. The pending-marker range and tree-state rules were ' +
    'deleted by lane GATE-3 (2026-10-08): the ledger records that a run happened, a marker only that one ' +
    'was owed.',
  source: 'META-HARNESS-BUILD-PLAN.md section 2 ("Smarter on its own, made structural"); operator rulings 2026-10-08; gate evaluation B section 4',

  // Holistic: one pass over the harness-runs tree, built once. Single sentinel => check() runs once.
  enumerate() {
    return ['fsi-app/.discipline/fitness/functions/F28-harness-run-integrity.mjs'];
  },

  check() {
    const root = getRepoRoot();
    const jsonFiles = globFiles([`${HARNESS_RUNS_REL}/**/*.json`]);
    const fileContents = {};
    for (const f of jsonFiles) fileContents[f] = readFileSync(join(root, f), 'utf8');
    const { byFamily } = scanArtifacts(fileContents);

    const problems = [...auditSchema(byFamily)];

    let familyDirs = [];
    try {
      familyDirs = readdirSync(join(root, HARNESS_RUNS_REL), { withFileTypes: true })
        .filter((e) => e.isDirectory())
        .map((e) => e.name);
    } catch {
      familyDirs = [];
    }

    for (const family of familyDirs) {
      if (!ALLOWED_FAMILIES.includes(family)) {
        problems.push(
          `UNKNOWN FAMILY - ${HARNESS_RUNS_REL}/${family}/ is not in run-artifact.mjs's ALLOWED_FAMILIES. ` +
            `Register it there AND add its own scripts/harness-runs/${family}/family.json, or remove the ` +
            `directory.`,
        );
      }
    }

    const ledger = readHarnessLedgerExport(root);
    const refDate = ledger.capturedAt ? new Date(ledger.capturedAt) : new Date();
    console.log(
      `  [F28] harness ledger export: ${ledger.present ? `present, ${ledger.rows.length} row(s), captured ${ledger.capturedAt ?? 'unknown'}` : 'absent'}; build mode ${BUILD_MODE ? 'on' : 'off'}`,
    );

    const tally = { current: 0, owed: 0, 'never-run': 0 };
    for (const family of ALLOWED_FAMILIES) {
      const validArtifacts = byFamily.get(family)?.valid ?? [];
      const governing = GOVERNING_FILES[family];
      if (!governing) continue; // defensive; ALLOWED_FAMILIES and GOVERNING_FILES are kept 1:1 by test

      const { hash: currentHash, problems: hashProblems } = safeHashGoverningFiles(
        family,
        governing,
        join(root, 'fsi-app'),
      );
      if (hashProblems.length) {
        problems.push(...hashProblems);
        continue; // no hash to compare the ledger against, or to couple the proposer attestation to, this pass
      }

      const currency = auditFamilyCurrency({
        family,
        liveHash: currentHash,
        ledgerRows: ledger.rows,
        ledgerPresent: ledger.present,
        registered: FAMILIES.find((f) => f.family === family)?.registered ?? null,
        refDate,
        buildMode: BUILD_MODE,
      });
      tally[currency.status]++;
      problems.push(...currency.problems);
      // a family with no ledger row is counted in the summary line below, not repeated once per family
      if (currency.status !== 'never-run') for (const n of currency.notices) console.log(`  [F28] ${n}`);

      const proposerPassPath = join(root, HARNESS_RUNS_REL, family, PROPOSER_PASS_FILE);
      problems.push(...auditProposerAttestation(family, validArtifacts, readIfExists(proposerPassPath)));
    }
    console.log(`  [F28] families current: ${tally.current}, run owed: ${tally.owed}, no ledger row: ${tally['never-run']}`);

    if (problems.length === 0) return PASS;
    return problems.map((msg) => violation(1, msg));
  },
};
