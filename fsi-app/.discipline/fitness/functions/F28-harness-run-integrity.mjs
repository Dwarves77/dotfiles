// F28: HARNESS-RUN INTEGRITY. The meta-harness layer's own enforcement gate (Wave MH-2, build plan section 2):
// a harness family's code must not drift away from the runs that prove it. Three rules, all against the
// COMMITTED TREE plus the committed harness ledger export (a static check, like every fitness function
// here: no DB, no network, no run of the harnesses themselves):
//
//   (a) SCHEMA: every artifact file under scripts/harness-runs/*/ validates against CONVENTION.md's
//       schema. Reuses validateRunArtifact (imported from scripts/lib/run-artifact.mjs, the module
//       Wave MH-1 built) rather than re-implementing the schema here, the exact "reuse by import"
//       discipline F27 uses for resolveSpecifier/isTestFile from F25.
//   (b) CURRENCY (lane GATE-3, 2026-10-08): a harness family is CURRENT when the harness ledger export
//       (fsi-app/.discipline/governance/harness-ledger-export.json, regenerated by
//       scripts/lib/export-harness-ledger.mjs from the harness_runs table) holds a row whose
//       `governing_hash` equals the family's LIVE governing-file hash (hashHarnessVersion over
//       GOVERNING_FILES[family], re-derived at check time). writeRunArtifact stamps `governing_hash` on
//       every artifact at run time, so a run is proof of the exact governing-file version it executed.
//       A family that is not current is reported, and it FAILS only when the evidence is old:
//         - rows exist but none at the live hash (the governing files changed after the last run): fails
//           when the family's newest row is older than the window (30 days; 90 in BUILD_MODE, where the
//           run is owed but the clock is paused), otherwise a notice that a run is owed;
//         - NO ledger row at all (nothing has run): in BUILD_MODE a notice, never a failure; outside build
//           mode it fails once the family is more than 30 days past its registration date.
//       The clock reads the export's own `capturedAt` (so a check is a pure function of committed files and
//       a stale snapshot is not misread as a stale family); with no export it reads the wall clock.
//   (c) PROPOSER ATTESTATION: a family with 2 or more valid artifacts (enough history for a proposer pass
//       to mean something, PROPOSER-RUNBOOK.md section 1's precondition) must carry a
//       LAST-PROPOSER-PASS.md that NAMES the latest artifact's run_id verbatim. A family with exactly one
//       artifact is not required to have one yet.
//
// WHAT THIS REPLACES. The pending-marker mechanism: a range rule (a governing file changed in a range, so
// the range must add a file under <family>/pending/) and a tree-state rule (a family with no artifact at
// the live hash must carry a pending file). Measured over 30 days (gate evaluation B): 12 failing runs, all
// PROCESS, the defect prevented in each was nothing (the fix was adding or deleting a markdown file),
// 138 markers added, 134 tracked, and no family had an artifact at its live hash so every family owed a
// marker permanently. A marker records that a run is owed; the ledger records that a run happened, which is
// the fact the gate actually wants. The 136 pending files and the pending/ convention were deleted by lane
// GATE-3 with this rewrite.
//
// COST: filesystem only. Reads scripts/harness-runs/**/*.json, each family's LAST-PROPOSER-PASS.md and the
// ledger export if present, and re-hashes GOVERNING_FILES from disk (same hashHarnessVersion the harnesses
// themselves use). No git, no network, no database, no model call, no schedule.
//
// Holistic, so it follows the F23/F25/F27 shape: enumerate() returns a single sentinel and the whole
// analysis runs once inside check().

